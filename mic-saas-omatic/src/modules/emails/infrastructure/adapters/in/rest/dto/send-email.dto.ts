import { ApiProperty } from '@nestjs/swagger';
import { IsEmail, IsNotEmpty, IsString, MaxLength } from 'class-validator';

export class SendEmailDto {
  @ApiProperty({
    description: 'Valid recipient email address conforming to RFC 5322',
    example: 'billing@acme.com',
  })
  @IsEmail({}, { message: 'The field "to" must be a valid RFC 5322 email address' })
  @IsNotEmpty({ message: 'The field "to" cannot be empty' })
  to!: string;

  @ApiProperty({
    description: 'Email subject line',
    example: 'SaaS-O-Matic: Optimization Proposal',
  })
  @IsString({ message: 'The field "subject" must be a string' })
  @IsNotEmpty({ message: 'The field "subject" cannot be empty' })
  @MaxLength(200, { message: 'The subject cannot exceed 200 characters' })
  subject!: string;

  @ApiProperty({
    description: 'Rich HTML body content generated by WYSIWYG editor',
    example: '<p>Dear customer, please review our proposal.</p>',
  })
  @IsString({ message: 'The field "htmlBody" must be a string' })
  @IsNotEmpty({ message: 'The field "htmlBody" cannot be empty' })
  htmlBody!: string;
}
